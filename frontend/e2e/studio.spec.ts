import {APP_URL,PREVIEW_URL} from './urls'
import {test,expect,type Page} from '@playwright/test'
import {mkdir} from 'node:fs/promises'

test('organizer → team → generate → edit → restore → submit → freeze, with sandbox and offline checks',async({browser,page})=>{
 test.setTimeout(120000)
 await mkdir('../artifacts',{recursive:true})
 const errors:string[]=[]
 page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/admin')
 await page.getByLabel('Organizer password',{exact:true}).fill('browser-test-password-2026')
 await page.getByRole('button',{name:'Open control room'}).click()
 await expect(page.getByText('Let’s make a great game jam.')).toBeVisible()
 const session=await (await page.request.get('/api/auth/session')).json()
 const headers={'Origin':APP_URL,'X-CSRF-Token':session.csrf}
 await page.request.patch('/api/admin/event',{headers,data:{frozen:false,paused:false,emergency_mode:false,primary:'mock',fallback:''}})
 await page.request.post('/api/admin/timer',{headers,data:{action:'reset',minutes:120}})
 await page.reload()
 await page.getByLabel('New team name').fill('Pixel Pioneers')
 await page.getByRole('button',{name:'Create team'}).click()
 const code=await page.locator('.issued-code').innerText()
 await page.getByRole('button',{name:'Close dialog'}).click()
 await page.getByRole('button',{name:'Start building',exact:true}).click()
 await expect(page.getByText('Ideas are turning into games.')).toBeVisible()
 await page.screenshot({path:'../artifacts/organizer-desktop.png',fullPage:true})
 const context=await browser.newContext({viewport:{width:1440,height:1100}})
 const team=await context.newPage()
 team.on('pageerror',e=>errors.push(e.message))
 await team.goto(APP_URL+'/')
 await team.screenshot({path:'../artifacts/login-desktop.png',fullPage:true})
 await team.getByLabel('Your team access code').fill(code)
 await team.getByRole('button',{name:'Enter the studio'}).click()
 await expect(team.getByText('Your ideas. Ready to play.')).toBeVisible()
 await team.screenshot({path:'../artifacts/studio-empty-desktop.png',fullPage:true})
 await team.getByRole('textbox',{name:'Describe your game or changes'}).fill('Create an arcade game about catching stars')
 await team.getByRole('button',{name:'Generate game',exact:true}).click()
 await expect(team.getByTitle('Cosmic Collector preview')).toBeVisible()
 await expect(team.getByText('11 requests left')).toBeVisible()
 const frame=team.frameLocator('iframe')
 await expect(frame.locator('canvas')).toBeVisible()
 await expect(frame.locator('#status')).toContainText('PLAYING')
 const iframe=team.locator('iframe')
 expect(await iframe.getAttribute('sandbox')).toBe('allow-scripts')
 const gameFrame=team.frames().find(f=>f.url().startsWith(PREVIEW_URL+'/play/'))!
 const isolation=await gameFrame.evaluate(async()=>{
   let parentBlocked=false,storageBlocked=false,cookiesBlocked=false,networkBlocked=false
   try{void parent.document.body}catch{parentBlocked=true}
   try{localStorage.setItem('attack','1')}catch{storageBlocked=true}
   try{void document.cookie}catch{cookiesBlocked=true}
   try{await fetch('https://blocked-network.invalid/probe')}catch{networkBlocked=true}
   return {parentBlocked,storageBlocked,cookiesBlocked,networkBlocked}
 })
 expect(isolation).toEqual({parentBlocked:true,storageBlocked:true,cookiesBlocked:true,networkBlocked:true})
 const startX=await gameFrame.evaluate(()=>{const c=document.querySelector('canvas')!;return c.toDataURL()})
 await iframe.click();await team.keyboard.press('ArrowRight',{delay:180})
 const moved=await gameFrame.evaluate(()=>document.querySelector('canvas')!.toDataURL())
 expect(moved).not.toBe(startX)
 await team.screenshot({path:'../artifacts/studio-playable-desktop.png',fullPage:true})
 // Exercise custom changes through the same complete-file version path. Demo mode says it is a starter.
 await team.getByRole('textbox',{name:'Describe your game or changes'}).fill('Add a puzzle game')
 await team.getByRole('button',{name:'Update game',exact:true}).click()
 await expect(team.getByTitle('Light Circuit preview')).toBeVisible()
 await expect(team.getByText('10 requests left')).toBeVisible()
 await team.getByRole('button',{name:/Version history/}).click()
 await team.locator('.history-list button').filter({hasText:'Cosmic Collector'}).click()
 await team.getByRole('button',{name:'Restore this version'}).click()
 await expect(team.getByTitle('Cosmic Collector preview')).toBeVisible()
 const downloadPromise=team.waitForEvent('download')
 await team.getByRole('link',{name:'Download standalone game'}).click()
 const download=await downloadPromise
 await download.saveAs('../artifacts/exported-game.html')
 expect(download.suggestedFilename()).toMatch(/\.html$/)
 await team.getByRole('button',{name:'Submit game',exact:true}).click()
 await team.getByLabel('Game title',{exact:true}).fill('Stardust from Tarkwa')
 await team.getByLabel('What’s your game about?').fill('Collect twenty stars with the arrow keys while dodging meteors.')
 await team.getByRole('button',{name:'Submit for judging'}).click()
 await expect(team.getByText('Your game is in!')).toBeVisible()
 // Responsive layout stays usable with every control within the viewport.
 await team.setViewportSize({width:390,height:844})
 await team.locator('iframe').scrollIntoViewIfNeeded()
 await expect(team.frameLocator('iframe').locator('#status')).toBeInViewport()
 await team.screenshot({path:'../artifacts/studio-mobile.png',fullPage:true})
 expect(await team.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.getByRole('button',{name:'End & freeze'}).click()
 await expect(page.getByText('Building has finished.')).toBeVisible()
 await team.reload()
 await expect(team.getByRole('button',{name:'Update submission'})).toBeDisabled()
 await expect(team.getByRole('link',{name:'Download standalone game'})).toBeVisible()
 await page.getByRole('button',{name:'Submission gallery'}).click()
 await expect(page.getByRole('heading',{name:'Stardust from Tarkwa'})).toBeVisible()
 await page.screenshot({path:'../artifacts/brand-revamp/submission-gallery.png',fullPage:true})
 await page.getByRole('button',{name:'Play game: Stardust from Tarkwa',exact:true}).click()
 await expect(page.getByTitle('Stardust from Tarkwa preview')).toBeVisible()
 await page.screenshot({path:'../artifacts/submission-gallery.png',fullPage:true})
 await page.getByRole('button',{name:'Close dialog'}).click()
 await expect(page.locator('iframe')).toHaveCount(0)
 // Export loads with all HTTP/HTTPS access disabled. Game uses only its own inline code.
 const offline=await browser.newContext()
 await offline.route(/^https?:/,route=>route.abort())
 const local=await offline.newPage()
 const {pathToFileURL}=await import('node:url')
 const {resolve}=await import('node:path')
 await local.goto(pathToFileURL(resolve('../artifacts/exported-game.html')).href)
 await expect(local.locator('#status')).toContainText('PLAYING')
 await local.keyboard.press('r');await expect(local.locator('#status')).toContainText('Score 0')
 await offline.close();await context.close()
 expect(errors).toEqual([])
})

test('five starter games initialize, respond to controls, and restart without external requests',async({browser,page})=>{
 await page.goto('/admin')
 await page.getByLabel('Organizer password',{exact:true}).fill('browser-test-password-2026')
 await page.getByRole('button',{name:'Open control room'}).click()
 await page.getByRole('button',{name:'Event settings'}).click()
 await page.getByRole('button',{name:'Reset to 120 minutes'}).click()
 await page.getByRole('button',{name:'Close dialog'}).click()
 if(await page.getByRole('button',{name:'Unfreeze entries'}).isVisible())await page.getByRole('button',{name:'Unfreeze entries'}).click()
 await page.getByRole('button',{name:'Start building',exact:true}).click()
 await page.getByLabel('New team name').fill('Starter Explorers')
 await page.getByRole('button',{name:'Create team'}).click()
 const code=await page.locator('.issued-code').innerText()
 const ctx=await browser.newContext(),p=await ctx.newPage()
 await p.goto(APP_URL+'/')
 await p.getByLabel('Your team access code').fill(code);await p.getByRole('button',{name:'Enter the studio'}).click()
 const errors:string[]=[];p.on('pageerror',e=>errors.push(e.message))
 for(const title of ['Cosmic Collector','Skybound','Light Circuit','Neon Dash','Garden Guardian']){
  await p.getByRole('button',{name:'Starter games',exact:true}).click()
  await p.locator('.starter-card').filter({has:p.getByRole('heading',{name:title,exact:true})}).getByRole('button',{name:'Start with this game'}).click()
  await expect(p.getByTitle(title+' preview')).toBeVisible()
  const f=p.frameLocator('iframe')
  await expect(f.locator('#status')).toContainText('PLAYING')
  await p.locator('iframe').click();await p.keyboard.press('ArrowRight',{delay:100});await p.keyboard.press('Space')
  await f.getByRole('button',{name:'Restart',exact:false}).click();await expect(f.locator('#status')).toContainText('PLAYING')
 }
 expect(errors).toEqual([])
 await expect(p.getByText('12 requests left')).toBeVisible()
 await ctx.close()
})
